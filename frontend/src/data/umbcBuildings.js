/**
 * Get building object by its unique ID
 * @param {string} id
 * @returns {object|undefined}
 */
export function getBuildingById(id) {
  if (!id) return undefined;
  return umbcBuildings.find(b => b.id === id);
}

/**
 * Get floors array for a building ID
 * @param {string} buildingId
 * @returns {string[]}
 */
export function getFloorsForBuilding(buildingId) {
  const building = getBuildingById(buildingId);
  return building ? building.floors : [];
}

/**
 * Filter buildings by name query
 * @param {string} query
 * @returns {object[]}
 */
export function searchBuildings(query) {
  if (!query || !query.trim()) return umbcBuildings;
  const q = query.toLowerCase().trim();
  return umbcBuildings.filter(b => b.name.toLowerCase().includes(q));
}

/**
 * Test whether a sheet record matches a given campus building and floor.
 * Strictly prevents cross-building leakage (e.g. ILSB blueprint showing on Administration Building).
 * 
 * @param {object} sheet
 * @param {string|null} buildingId
 * @param {string|null} floorId
 * @returns {boolean}
 */
export function sheetMatchesBuildingAndFloor(sheet, buildingId, floorId) {
  if (!sheet) return false;
  if (!buildingId && !floorId) return true;

  const bObj = getBuildingById(buildingId);
  const bName = bObj ? bObj.name.toLowerCase() : '';
  const sBldId = sheet.building_id ? sheet.building_id.toLowerCase().trim() : null;
  const sBldName = sheet.building_name ? sheet.building_name.toLowerCase().trim() : '';
  const sName = (sheet.name || '').toLowerCase();
  const fLower = floorId ? floorId.toLowerCase().trim() : '';

  // 1. Verify Building Matching
  if (buildingId) {
    const bIdLower = buildingId.toLowerCase().trim();
    let buildingMatches = false;

    if (sBldId) {
      buildingMatches = (
        sBldId === bIdLower ||
        sBldId === `umbc-${bIdLower}` ||
        bIdLower === `umbc-${sBldId}` ||
        sBldId.replace(/^umbc-/, '') === bIdLower.replace(/^umbc-/, '')
      );
    } else if (sBldName && bName) {
      buildingMatches = (
        sBldName === bName ||
        sBldName.includes(bName) ||
        bName.includes(sBldName)
      );
    } else if (bName) {
      // If sheet has no explicit building_id/name, only match if the sheet name explicitly contains this building's full name
      buildingMatches = sName.includes(bName);
    }

    if (!buildingMatches) return false;
  }

  // 2. Verify Floor Matching
  if (floorId) {
    if (sheet.floor_level) {
      return sheet.floor_level.toLowerCase().trim() === fLower;
    }
    const sNum = (sheet.sheet_number || '').toLowerCase();
    return sName.includes(fLower) || sNum.includes(fLower);
  }

  return true;
}
